# Helper Functions
# ============================================================================

def parse_conditioning_frames(frames_str):
    """Parse comma-separated frame indices into a sorted list of ints."""
    frames = sorted(int(x.strip()) for x in frames_str.split(','))
    for f in frames:
        if f < 0 or f > 11:
            raise ValueError(f"Frame index {f} out of range [0, 11]")
    if len(frames) != len(set(frames)):
        raise ValueError(f"Duplicate frame indices in: {frames_str}")
    return frames


def parse_custom_frame_specs(raw_specs):
    """Parse --custom-frame arguments into a dict keyed by frame index.

    Returns
    -------
    dict[int, tuple[int, int, int, int]]
        {frame_idx: (year, month, day, hour)}
    """
    specs = {}
    if not raw_specs:
        return specs
    for cf in raw_specs:
        frame_idx = int(cf[0])
        if frame_idx in specs:
            raise ValueError(
                f"Duplicate --custom-frame for frame index {frame_idx}"
            )
        specs[frame_idx] = (int(cf[1]), int(cf[2]), int(cf[3]), int(cf[4]))
    return specs


def parse_tc_frame_specs(raw_specs):
    """Parse --tc-frame arguments into a dict keyed by frame index.

    Returns
    -------
    dict[int, tuple[torch.Tensor, torch.Tensor]]
        {frame_idx: (lats_tensor, lons_tensor)}
    """
    specs = {}
    if not raw_specs:
        return specs
    for tf in raw_specs:
        frame_idx = int(tf[0])
        if frame_idx in specs:
            raise ValueError(
                f"Duplicate --tc-frame for frame index {frame_idx}"
            )
        lats = torch.tensor([float(x.strip()) for x in tf[1].split(',')])
        lons = torch.tensor([float(x.strip()) for x in tf[2].split(',')])
        if len(lats) != len(lons):
            raise ValueError(
                f"TC frame {frame_idx}: latitudes ({len(lats)}) and "
                f"longitudes ({len(lons)}) must have the same length"
            )
        specs[frame_idx] = (lats, lons)
    return specs


def validate_frame_specs(conditioning_frames, custom_specs, tc_specs):
    """Validate that custom and TC frame specs are consistent with conditioning frames.

    Each conditioning frame must come from exactly one source: default ERA5
    (NaN-padded), custom ERA5 (NaN-padded), or TC guidance.  This function
    enforces mutual exclusivity across all three sources.
    """
    for f in custom_specs:
        if f not in conditioning_frames:
            raise ValueError(
                f"Custom frame index {f} is not in conditioning_frames {conditioning_frames}"
            )
    for f in tc_specs:
        if f not in conditioning_frames:
            raise ValueError(
                f"TC frame index {f} is not in conditioning_frames {conditioning_frames}"
            )
    overlap = set(custom_specs) & set(tc_specs)
    if overlap:
        raise ValueError(
            f"Frame indices {overlap} cannot be both custom ERA5 and TC guidance"
        )
    # Verify every conditioning frame maps to exactly one source
    era5_set = set(conditioning_frames) - set(custom_specs) - set(tc_specs)
    assert era5_set | set(custom_specs) | set(tc_specs) == set(conditioning_frames), (
        f"Source sets do not cover all conditioning frames: "
        f"era5={era5_set}, custom={set(custom_specs)}, tc={set(tc_specs)}, "
        f"conditioning={set(conditioning_frames)}"
    )


def squeeze_tc_frame(tc_raw):
    """Normalize TC guidance output to shape [1, 1, C, H]."""
    tc_frame = tc_raw
    while tc_frame.ndim > 2:
        assert tc_frame.shape[0] == 1, (
            f"Expected singleton dimension but got shape {tc_frame.shape}"
        )
        tc_frame = tc_frame.squeeze(0)
    return tc_frame.unsqueeze(0).unsqueeze(0).cpu()


