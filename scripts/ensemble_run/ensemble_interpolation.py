#!/usr/bin/env python3
"""
Ensemble Interpolation Script

Generates ensembles of interpolated weather trajectories with flexible
conditioning.  Any subset of the 12 output frames (0-11) can be conditioned
on, and each conditioning frame can come from one of three sources:

  - ERA5 (default):    the corresponding frame from the start-time window,
                       NaN-padded to the full 45-variable model layout
  - Custom ERA5 frame: a NaN-padded ERA5 frame from a different date/time
  - TC guidance:       a frame generated by the TC guidance model

The ensemble_size parameter controls how many ensemble members are generated.
All members share the same conditioning but receive different stochastic
noise, producing diverse trajectories. Large ensembles are automatically
chunked into micro-batches of batch_size to fit in GPU memory.

Pipeline: Load raw ERA5 zarr data (lat/lon) -> Regrid to healpix and pad non-ERA5
          variables with NaN -> Interpolate with CBottleInterpolate
          (healpix in, healpix out) -> Save ensemble output as zarr stores
          on the native HEALPix grid; the ERA5 reference store stays on
          lat/lon for downstream regridding flexibility.
"""

import argparse
import os
import shutil
import sys
from datetime import datetime, timedelta

import numpy as np
import torch
import zarr

# Add scripts/_shared to path; its custom_utils symlink resolves the import.
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '_shared'))
from custom_utils.interpolation_utils import (  # noqa: E402
    STORED_VARIABLES,
    CBottleUtils,
    subset_variables,
)


