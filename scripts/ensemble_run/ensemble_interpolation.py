def setup_args():
    """Setup command line arguments."""
    parser = argparse.ArgumentParser(
        description='Ensemble Interpolation: generate ensemble members with '
                    'flexible frame conditioning'
    )

    # Date/Time Configuration
    parser.add_argument('--start-year', type=int, required=True,
                        help='Start year for the 12-frame window')
    parser.add_argument('--start-month', type=int, required=True,
                        help='Start month (1-12)')
    parser.add_argument('--start-day', type=int, required=True,
                        help='Start day of month')
    parser.add_argument('--start-hour', type=int, default=0,
                        help='Start hour (0, 6, 12, or 18), default: 0')

    # Conditioning Frames (flexible)
    parser.add_argument('--conditioning-frames', type=str, required=True,
                        help='Comma-separated frame indices (0-11) to condition on, '
                             'e.g. "0,11" for both ends, "0" for start-only, '
                             '"0,3,6,11" for four frames')

    # Ensemble Configuration
    parser.add_argument('--ensemble-size', type=int, default=4,
                        help='Total number of ensemble members to generate, default: 4')
    parser.add_argument('--member-offset', type=int, default=0,
                        help='Offset from 0 for saving subset chunks. default: 0')
    parser.add_argument('--members-to-run', type=int, default=None,
                        help='Override the number of members generated by this specific job, default: matches ensemble_size')
    parser.add_argument('--batch-size', type=int, default=1,
                        help='Micro-batch size per forward pass (GPU limit), default: 1')
    parser.add_argument('--random-seed', type=int, default=None,
                        help='Random seed for model, default: None')

    # Output
    parser.add_argument('--output-dir', type=str, required=True,
                        help='Output directory for ensemble zarr stores')

    # Model Configuration
    parser.add_argument('--data-path', type=str,
                        default='/projectnb/eb-general/shared_data/data/raw/era5_raw_zarr',
                        help='Path to ERA5 raw zarr root directory')
    parser.add_argument('--package-timeout', type=int, default=600,
                        help='Package download timeout in seconds, default: 600')

    # Custom ERA5 frames (repeatable).  Each occurrence specifies one frame
    # whose conditioning data comes from an arbitrary ERA5 date instead of
    # the natural window.
    #   --custom-frame FRAME_IDX YEAR MONTH DAY HOUR
    parser.add_argument('--custom-frame', action='append', nargs=5,
                        metavar=('FRAME', 'YEAR', 'MONTH', 'DAY', 'HOUR'),
                        help='Custom ERA5 frame: FRAME_IDX YEAR MONTH DAY HOUR '
                             '(repeatable for multiple frames)')

    # TC guidance frames (repeatable).  Each occurrence specifies one frame
    # whose conditioning data is generated by the TC guidance model.
    # Latitudes and longitudes use colon separators within each argument
    # (commas are used by argparse for list items).
    #   --tc-frame FRAME_IDX LAT1,LAT2,... LON1,LON2,...
    parser.add_argument('--tc-frame', action='append', nargs=3,
                        metavar=('FRAME', 'LATS', 'LONS'),
                        help='TC guidance frame: FRAME_IDX LAT1,LAT2,... LON1,LON2,... '
                             '(repeatable for multiple frames)')

    return parser.parse_args()


